export function t(lang: string, key: string, vars?: Record<string, string | number>): string {
  const table = STRINGS[lang];
  const text = (table && key in table ? table[key as Key] : undefined) ?? STRINGS.en[key as Key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (vars[name] != null ? String(vars[name]) : match));
}

